  bool _hasPhoneGeometry({
    required double physicalWidth,
    required double physicalHeight,
    required double devicePixelRatio,
  }) {
    final logicalShort = math.min(physicalWidth, physicalHeight) / devicePixelRatio;
    final aspect = math.max(physicalWidth, physicalHeight) / math.min(physicalWidth, physicalHeight);
    return logicalShort >= 240 && logicalShort < 600 && aspect >= 4 / 3 && aspect <= 3;
  }

