final class _DeviceDisplayModelCollector {
  Map<String, Object?> validateSourceManifests() {
    final androidDirectory = Directory(
      '${Directory.current.path}/tool/device_display_model/android_collector',
    );
    final iosDirectory = Directory(
      '${Directory.current.path}/tool/device_display_model/ios_device_collector',
    );
    final androidSourceHash = _collectorSourceHash(androidDirectory);
    final iosSourceHash = _collectorSourceHash(iosDirectory);
    final iosHeader = File('${iosDirectory.path}/collector_source_hash.h');
    final expectedIosHeader =
        '// Generated by generate_ios_device_collector_provenance.sh.\n'
        '#define OMF_DEVICE_DISPLAY_COLLECTOR_SOURCE_HASH @"$iosSourceHash"\n';
    return <String, Object?>{
      'androidCollectorSourceHash': androidSourceHash,
      'iosCollectorSourceHash': iosSourceHash,
      'iosCollectorSourceManifestFresh': iosHeader.existsSync() && iosHeader.readAsStringSync() == expectedIosHeader,
    };
  }

  Future<Map<String, Object?>> validateTooling() async {
    final android = await _androidCollectorApk();
    final sources = validateSourceManifests();
    return <String, Object?>{
      'androidCollectorBuiltAndLinted': android != null,
      'androidCollectorSourceHash': android?.sourceHash,
      'iosCollectorSourceManifestFresh': sources['iosCollectorSourceManifestFresh'],
      'iosCollectorSourceHash': sources['iosCollectorSourceHash'],
    };
  }

  Future<Map<String, Object?>> collect({
    List<String> iosRecordPaths = const [],
    String? iosDeviceAppPath,
  }) async {
    final android = await _collectAndroid();
    final apple = await _collectApple(
      iosDeviceAppPath: iosDeviceAppPath,
    );
    final connectedIosRecords = (apple.remove('connectedRecords')! as List<Object?>).cast<Map<String, Object?>>();
    final iosRecords = <Map<String, Object?>>[];
    for (final path in iosRecordPaths) {
      final decoded = jsonDecode(File(path).readAsStringSync());
      final importedRecords = switch (decoded) {
        final Map<String, Object?> record => <Map<String, Object?>>[record],
        final List<Object?> records => records.map((value) => value! as Map<String, Object?>).toList(),
        _ => throw const FormatException(
          'An iOS record input must be a JSON object or array.',
        ),
      };
      for (final imported in importedRecords) {
        final record = _importIosRecord(imported);
        if (record != null) {
          iosRecords.add(record);
        }
      }
    }
    apple['exactLabelCount'] = iosRecords.length + connectedIosRecords.length;
    final collectedRecords = <Map<String, Object?>>[
      ...(android['records']! as List<Map<String, Object?>>),
      ...iosRecords,
      ...connectedIosRecords,
    ];
    final recordByObservation = <String, Map<String, Object?>>{};
    for (final record in collectedRecords) {
      final observationHash = record['sourceObservationHash']! as String;
      final existing = recordByObservation[observationHash];
      if (existing == null ||
          (existing['maskCollisionGroupHash'] == null && record['maskCollisionGroupHash'] != null)) {
        recordByObservation[observationHash] = record;
      }
    }
    final records = recordByObservation.values.toList()..sort(_compareRecords);

    return <String, Object?>{
      'schemaVersion': 1,
      'inventory': <String, Object?>{
        'android': android['inventory'],
        'apple': apple,
      },
      'records': records,
    };
  }

  Map<String, Object?>? _importIosRecord(Map<String, Object?> imported) {
    if (imported['platform'] != 'ios' ||
        (imported['sourceKind'] != 'ios26_public_uikit_concentric_corner' &&
            imported['sourceKind'] != 'ios_legacy_private_display_corner_selector')) {
      return null;
    }
    final width = imported['physicalWidth'];
    final height = imported['physicalHeight'];
    final topRadius = imported['topRadiusPhysical'];
    final bottomRadius = imported['bottomRadiusPhysical'];
    final density = imported['devicePixelRatio'];
    if (width is! num ||
        height is! num ||
        topRadius is! num ||
        bottomRadius is! num ||
        density is! num ||
        width <= 0 ||
        height <= 0 ||
        topRadius < 0 ||
        bottomRadius < 0 ||
        !width.toDouble().isFinite ||
        !height.toDouble().isFinite ||
        !topRadius.toDouble().isFinite ||
        !bottomRadius.toDouble().isFinite ||
        !density.toDouble().isFinite ||
        topRadius > math.min(width.toDouble(), height.toDouble()) / 2 ||
        bottomRadius > math.min(width.toDouble(), height.toDouble()) / 2 ||
        !_hasPhoneGeometry(
          physicalWidth: width.toDouble(),
          physicalHeight: height.toDouble(),
          devicePixelRatio: density.toDouble(),
        )) {
      return null;
    }
    final viewWidth = imported['viewPhysicalWidth'];
    final viewHeight = imported['viewPhysicalHeight'];
    if ((viewWidth == null) != (viewHeight == null) ||
        !_isValidOptionalDimension(viewWidth, maximum: width.toDouble()) ||
        !_isValidOptionalDimension(viewHeight, maximum: height.toDouble())) {
      return null;
    }
    for (final entry in <String, double>{
      'viewPaddingLeftPhysical': width.toDouble(),
      'viewPaddingTopPhysical': height.toDouble(),
      'viewPaddingRightPhysical': width.toDouble(),
      'viewPaddingBottomPhysical': height.toDouble(),
    }.entries) {
      if (!_isValidOptionalInset(imported[entry.key], maximum: entry.value)) {
        return null;
      }
    }
    for (final key in const <String>[
      'familyGroupHash',
      'generationGroupHash',
      'oemGroupHash',
      'maskCollisionGroupHash',
    ]) {
      final value = imported[key];
      if (value != null &&
          (value is! String ||
              !RegExp(
                r'^sha256:(?:[0-9a-f]{16}|[0-9a-f]{64})$',
              ).hasMatch(value))) {
        return null;
      }
    }
    final chronologyRank = imported['chronologyRank'];
    if (chronologyRank != null && (chronologyRank is! int || chronologyRank < 0)) {
      return null;
    }
    return _record(
      platform: 'ios',
      sourceKind: imported['sourceKind']! as String,
      physicalWidth: width,
      physicalHeight: height,
      viewPhysicalWidth: viewWidth as num?,
      viewPhysicalHeight: viewHeight as num?,
      devicePixelRatio: density,
      viewPaddingLeftPhysical: imported['viewPaddingLeftPhysical'] as num?,
      viewPaddingTopPhysical: imported['viewPaddingTopPhysical'] as num?,
      viewPaddingRightPhysical: imported['viewPaddingRightPhysical'] as num?,
      viewPaddingBottomPhysical: imported['viewPaddingBottomPhysical'] as num?,
      topRadiusPhysical: topRadius,
      bottomRadiusPhysical: bottomRadius,
      provenance: <String, Object?>{
        for (final key in const [
          'familyGroupHash',
          'generationGroupHash',
          'oemGroupHash',
          'maskCollisionGroupHash',
          'chronologyRank',
        ])
          if (imported[key] != null) key: imported[key],
      },
      labelAuthority: imported['sourceKind'] == 'ios26_public_uikit_concentric_corner'
          ? 'ios26_public_uikit_concentric_corner'
          : 'ios_tool_only_private_selector',
      cornerClassification: topRadius == 0 && bottomRadius == 0 ? 'square' : 'rounded',
    );
  }

  Future<Map<String, Object?>> _collectAndroid() async {
    final sdkPath = Platform.environment['ANDROID_HOME'] ?? Platform.environment['ANDROID_SDK_ROOT'];
    final records = <Map<String, Object?>>[];
    var skinCount = 0;
    var skinLabelCount = 0;
    var avdCount = 0;
    var connectedDeviceCount = 0;
    var connectedEmulatorDeviceCount = 0;
    var connectedEligibleDeviceCount = 0;
    var connectedCollectorAttemptCount = 0;
    var connectedLabelCount = 0;
    var connectedExactLabelCount = 0;
    var connectedLegacyLabelCount = 0;
    var connectedCollectorFailureCount = 0;
    String? connectedCollectorSourceHash;
    var avdDensityJoinCount = 0;

    if (sdkPath != null) {
      final skinsDirectory = Directory('$sdkPath/skins');
      final skinDirectories = skinsDirectory.existsSync()
          ? (skinsDirectory.listSync().whereType<Directory>().toList()
              ..sort((left, right) => left.path.compareTo(right.path)))
          : <Directory>[];
      final skinNames = <String>{
        for (final directory in skinDirectories) directory.path.split('/').last,
      };
      final skinGeometry = <String, ({int width, int height})>{};
      for (final directory in skinDirectories) {
        final geometry = _androidSkinGeometry(directory);
        if (geometry != null) {
          skinGeometry[directory.path.split('/').last] = geometry;
        }
      }
      final avdInventory = await _readAvdInventory(
        sdkPath,
        availableSkinNames: skinNames,
        skinGeometry: skinGeometry,
      );
      avdCount = avdInventory.count;
      if (skinsDirectory.existsSync()) {
        skinCount = skinDirectories.length;
        for (final directory in skinDirectories) {
          final skinName = directory.path.split('/').last;
          final record = _readAndroidSkin(
            directory,
            devicePixelRatio: avdInventory.densityBySkin[skinName],
            apiLevel: avdInventory.apiBySkin[skinName],
          );
          if (record != null) {
            records.add(record);
            skinLabelCount += 1;
            if (record['devicePixelRatio'] != null) {
              avdDensityJoinCount += 1;
            }
          }
        }
      }

      final adb = File('$sdkPath/platform-tools/adb');
      if (adb.existsSync()) {
        final connected = await _collectConnectedAndroid(adb.path);
        connectedDeviceCount = connected.deviceCount;
        connectedEmulatorDeviceCount = connected.emulatorDeviceCount;
        connectedEligibleDeviceCount = connected.eligibleDeviceCount;
        connectedCollectorAttemptCount = connected.attemptedDeviceCount;
        connectedLabelCount = connected.records.length;
        connectedExactLabelCount = connected.records
            .where(
              (record) => record['sourceKind'] == 'android_api31_window_insets',
            )
            .length;
        connectedLegacyLabelCount = connected.records
            .where(
              (record) => record['sourceKind'] == 'android_legacy_default_display_resource',
            )
            .length;
        connectedCollectorFailureCount = connected.failureCount;
        connectedCollectorSourceHash = connected.collectorSourceHash;
        records.addAll(connected.records);
      }
    }

    return <String, Object?>{
      'inventory': <String, Object?>{
        'sdkFound': sdkPath != null,
        'skinCount': skinCount,
        'skinLabelCount': skinLabelCount,
        'avdCount': avdCount,
        'avdDensityJoinCount': avdDensityJoinCount,
        'connectedDeviceCount': connectedDeviceCount,
        'connectedEmulatorDeviceCount': connectedEmulatorDeviceCount,
        'connectedEligibleDeviceCount': connectedEligibleDeviceCount,
        'connectedCollectorAttemptCount': connectedCollectorAttemptCount,
        'connectedLabelCount': connectedLabelCount,
        'connectedExactLabelCount': connectedExactLabelCount,
        'connectedLegacyLabelCount': connectedLegacyLabelCount,
        'connectedCollectorFailureCount': connectedCollectorFailureCount,
        'collectorSourceHash': connectedCollectorSourceHash,
      },
      'records': records,
    };
  }

  Map<String, Object?>? _readAndroidSkin(
    Directory directory, {
    required double? devicePixelRatio,
    required int? apiLevel,
  }) {
    final layout = File('${directory.path}/layout');
    if (!layout.existsSync()) {
      return null;
    }
    final contents = layout.readAsStringSync();
    final displayMatch = RegExp(
      r'display\s*\{([^}]*)\}',
      dotAll: true,
    ).firstMatch(contents);
    if (displayMatch == null) {
      return null;
    }
    final display = displayMatch.group(1)!;
    final width = _integer(display, 'width');
    final height = _integer(display, 'height');
    final radius = _integer(display, 'corner_radius');
    if (width == null ||
        height == null ||
        radius == null ||
        radius <= 0 ||
        devicePixelRatio == null ||
        !_hasPhoneGeometry(
          physicalWidth: width.toDouble(),
          physicalHeight: height.toDouble(),
          devicePixelRatio: devicePixelRatio,
        )) {
      return null;
    }
    return _record(
      sourceKind: 'android_sdk_skin_avd_join',
      physicalWidth: width,
      physicalHeight: height,
      devicePixelRatio: devicePixelRatio,
      viewPaddingTopPhysical: null,
      viewPaddingBottomPhysical: null,
      topRadiusPhysical: radius,
      bottomRadiusPhysical: radius,
      provenance: _anonymousProvenance(directory.path.split('/').last),
      sourceApiLevel: apiLevel,
      labelAuthority: 'android_emulator_skin_resource',
      cornerClassification: 'rounded',
    );
  }

  ({int width, int height})? _androidSkinGeometry(Directory directory) {
    final layout = File('${directory.path}/layout');
    if (!layout.existsSync()) {
      return null;
    }
    final display = RegExp(
      r'display\s*\{([^}]*)\}',
      dotAll: true,
    ).firstMatch(layout.readAsStringSync())?.group(1);
    if (display == null) {
      return null;
    }
    final width = _integer(display, 'width');
    final height = _integer(display, 'height');
    return width == null || height == null ? null : (width: width, height: height);
  }

  Future<
    ({
      int count,
      Map<String, double> densityBySkin,
      Map<String, int> apiBySkin,
    })
  >
  _readAvdInventory(
    String sdkPath, {
    required Set<String> availableSkinNames,
    required Map<String, ({int width, int height})> skinGeometry,
  }) async {
    final avdManager = File('$sdkPath/cmdline-tools/latest/bin/avdmanager');
    if (!avdManager.existsSync()) {
      return (
        count: 0,
        densityBySkin: <String, double>{},
        apiBySkin: <String, int>{},
      );
    }
    final result = await _runBounded(
      avdManager.path,
      const ['list', 'avd'],
    );
    if (result == null || result.exitCode != 0) {
      return (
        count: 0,
        densityBySkin: <String, double>{},
        apiBySkin: <String, int>{},
      );
    }
    final output = result.stdout;
    final avdCount = RegExp(
      r'^\s*Name:\s*.+$',
      multiLine: true,
    ).allMatches(output).length;
    final densities = <String, Set<double>>{};
    final apis = <String, Set<int>>{};
    for (final pathMatch in RegExp(
      r'^\s*Path:\s*(.+\.avd)\s*$',
      multiLine: true,
    ).allMatches(output)) {
      final config = File('${pathMatch.group(1)!}/config.ini');
      if (!config.existsSync()) {
        continue;
      }
      final properties = <String, String>{};
      for (final line in config.readAsLinesSync()) {
        final separator = line.indexOf('=');
        if (separator <= 0) {
          continue;
        }
        properties[line.substring(0, separator)] = line.substring(separator + 1);
      }
      final density = double.tryParse(properties['hw.lcd.density'] ?? '');
      final width = int.tryParse(properties['hw.lcd.width'] ?? '');
      final height = int.tryParse(properties['hw.lcd.height'] ?? '');
      final exactSkins = <String>{
        for (final key in const <String>['skin.name', 'hw.device.name'])
          if (properties[key] case final value?)
            if (availableSkinNames.contains(value)) value,
      };
      if (exactSkins.length != 1 || density == null || density <= 0 || width == null || height == null) {
        continue;
      }
      final skin = exactSkins.single;
      final expected = skinGeometry[skin];
      if (expected == null ||
          math.min(width, height) != math.min(expected.width, expected.height) ||
          math.max(width, height) != math.max(expected.width, expected.height)) {
        continue;
      }
      densities.putIfAbsent(skin, () => <double>{}).add(density / 160);
      final imagePath = properties['image.sysdir.1'];
      final api = imagePath == null
          ? null
          : int.tryParse(
              RegExp(r'android-(\d+)').firstMatch(imagePath)?.group(1) ?? '',
            );
      if (api != null) {
        apis.putIfAbsent(skin, () => <int>{}).add(api);
      }
    }
    return (
      count: avdCount,
      densityBySkin: <String, double>{
        for (final entry in densities.entries)
          if (entry.value.length == 1) entry.key: entry.value.single,
      },
      apiBySkin: <String, int>{
        for (final entry in apis.entries)
          if (entry.value.length == 1) entry.key: entry.value.single,
      },
    );
  }

  Future<
    ({
      int deviceCount,
      int emulatorDeviceCount,
      int eligibleDeviceCount,
      int attemptedDeviceCount,
      int failureCount,
      String? collectorSourceHash,
      List<Map<String, Object?>> records,
    })
  >
  _collectConnectedAndroid(String adbPath) async {
    final devicesResult = await _runBounded(adbPath, const ['devices']);
    if (devicesResult == null || devicesResult.exitCode != 0) {
      return (
        deviceCount: 0,
        emulatorDeviceCount: 0,
        eligibleDeviceCount: 0,
        attemptedDeviceCount: 0,
        failureCount: 0,
        collectorSourceHash: null,
        records: <Map<String, Object?>>[],
      );
    }
    final serials = <String>[];
    for (final line in devicesResult.stdout.split('\n')) {
      final match = RegExp(r'^(\S+)\s+device(?:\s|$)').firstMatch(line);
      if (match != null) {
        serials.add(match.group(1)!);
      }
    }
    serials.sort();

    final eligible = <({String serial, int sdkLevel})>[];
    var emulatorDeviceCount = 0;
    for (final serial in serials) {
      final emulatorResult = await _runBounded(adbPath, <String>[
        '-s',
        serial,
        'shell',
        'getprop',
        'ro.kernel.qemu',
      ]);
      if (emulatorResult == null || emulatorResult.exitCode != 0) {
        continue;
      }
      final emulatorMarker = emulatorResult.stdout.trim();
      if (emulatorMarker == '1') {
        emulatorDeviceCount += 1;
        continue;
      }
      // Android hardware normally exposes this property as either `0` or an
      // empty value. Any other successful value is not affirmative hardware
      // evidence, so keep the transport out of the physical-device corpus.
      if (emulatorMarker.isNotEmpty && emulatorMarker != '0') {
        continue;
      }
      final sdkResult = await _runBounded(adbPath, <String>[
        '-s',
        serial,
        'shell',
        'getprop',
        'ro.build.version.sdk',
      ]);
      final sdkLevel = sdkResult?.exitCode == 0 ? int.tryParse(sdkResult!.stdout.trim()) : null;
      if (sdkLevel != null && sdkLevel >= 24) {
        eligible.add((serial: serial, sdkLevel: sdkLevel));
      }
    }
    if (eligible.isEmpty) {
      return (
        deviceCount: serials.length,
        emulatorDeviceCount: emulatorDeviceCount,
        eligibleDeviceCount: 0,
        attemptedDeviceCount: 0,
        failureCount: 0,
        collectorSourceHash: null,
        records: <Map<String, Object?>>[],
      );
    }

    final collector = await _androidCollectorApk();
    if (collector == null) {
      return (
        deviceCount: serials.length,
        emulatorDeviceCount: emulatorDeviceCount,
        eligibleDeviceCount: eligible.length,
        attemptedDeviceCount: 0,
        failureCount: eligible.length,
        collectorSourceHash: null,
        records: <Map<String, Object?>>[],
      );
    }

    final records = <Map<String, Object?>>[];
    var attemptedDeviceCount = 0;
    var failureCount = 0;
    for (var index = 0; index < eligible.length; index += 1) {
      final device = eligible[index];
      attemptedDeviceCount += 1;
      final nonce = DeviceDisplayModelEncoding.fingerprint(
        <String, Object?>{
          'serial': device.serial,
          'process': pid,
          'index': index,
          'time': DateTime.now().microsecondsSinceEpoch,
        },
      );
      var installAttempted = false;
      try {
        installAttempted = true;
        final install = await _runBounded(adbPath, <String>[
          '-s',
          device.serial,
          'install',
          '-r',
          collector.path,
        ]);
        if (install == null || install.exitCode != 0) {
          failureCount += 1;
          continue;
        }
        await _runBounded(adbPath, <String>[
          '-s',
          device.serial,
          'shell',
          'am',
          'force-stop',
          _androidCollectorPackage,
        ]);
        final launch = await _runBounded(adbPath, <String>[
          '-s',
          device.serial,
          'shell',
          'am',
          'start',
          '-W',
          '-n',
          '$_androidCollectorPackage/.CornerRadiusCollectorActivity',
          '--es',
          'nonce',
          nonce,
        ]);
        if (launch == null || launch.exitCode != 0) {
          failureCount += 1;
          continue;
        }
        Map<String, Object?>? payload;
        for (var attempt = 0; attempt < 20; attempt += 1) {
          final pulled = await _runBounded(adbPath, <String>[
            '-s',
            device.serial,
            'exec-out',
            'run-as',
            _androidCollectorPackage,
            'cat',
            'files/device_display_record.json',
          ]);
          if (pulled?.exitCode == 0) {
            try {
              payload = jsonDecode(pulled!.stdout) as Map<String, Object?>;
            } on FormatException {
              payload = null;
            }
          }
          if (payload?['nonce'] == nonce) {
            break;
          }
          payload = null;
          await Future<void>.delayed(const Duration(milliseconds: 250));
        }
        final record = payload == null
            ? null
            : _importAndroidWindowInsetsRecord(
                payload,
                expectedNonce: nonce,
                sdkLevel: device.sdkLevel,
                expectedSourceHash: collector.sourceHash,
              );
        if (record == null) {
          failureCount += 1;
          continue;
        }
        record.addAll(
          await _connectedAndroidProvenance(adbPath, device.serial),
        );
        _updateSourceObservationHash(record);
        records.add(record);
      } finally {
        if (installAttempted) {
          await _runBounded(adbPath, <String>[
            '-s',
            device.serial,
            'uninstall',
            _androidCollectorPackage,
          ]);
        }
      }
    }
    return (
      deviceCount: serials.length,
      emulatorDeviceCount: emulatorDeviceCount,
      eligibleDeviceCount: eligible.length,
      attemptedDeviceCount: attemptedDeviceCount,
      failureCount: failureCount,
      collectorSourceHash: collector.sourceHash,
      records: records,
    );
  }

  static const _androidCollectorPackage = 'dev.ventairy.oh_my_flutter.device_display_model_collector';

  Future<({String path, String sourceHash})?> _androidCollectorApk() async {
    final configured = Platform.environment['OMF_DEVICE_DISPLAY_ANDROID_COLLECTOR_TEST_APK'];
    if (configured != null && Platform.environment['OMF_DEVICE_DISPLAY_ALLOW_TEST_COLLECTOR'] == '1') {
      final sourceHash = Platform.environment['OMF_DEVICE_DISPLAY_ANDROID_COLLECTOR_TEST_SOURCE_HASH'];
      final file = File(configured);
      if (!file.isAbsolute ||
          !file.existsSync() ||
          sourceHash == null ||
          !RegExp(r'^sha256:[0-9a-f]{64}$').hasMatch(sourceHash)) {
        return null;
      }
      return await _apkContainsAndroidCollectorSource(
            file.path,
            sourceHash,
          )
          ? (path: file.path, sourceHash: sourceHash)
          : null;
    }
    final collectorDirectory = Directory(
      '${Directory.current.path}/tool/device_display_model/android_collector',
    );
    final apk = File(
      '${collectorDirectory.path}/app/build/outputs/apk/debug/app-debug.apk',
    );
    final wrapper = File('${Directory.current.path}/example/android/gradlew');
    if (!wrapper.existsSync()) {
      return null;
    }
    final sourceHash = _androidCollectorSourceHash(collectorDirectory);
    final build = await _runBounded(
      wrapper.path,
      <String>[
        '-p',
        collectorDirectory.path,
        ':app:assembleDebug',
        ':app:lintDebug',
        '--rerun-tasks',
        '--console=plain',
      ],
      timeout: const Duration(minutes: 5),
    );
    if (build == null || build.exitCode != 0) {
      return null;
    }
    if (!apk.existsSync()) {
      return null;
    }
    return await _apkContainsAndroidCollectorSource(apk.path, sourceHash)
        ? (path: apk.path, sourceHash: sourceHash)
        : null;
  }

  String _androidCollectorSourceHash(Directory collectorDirectory) {
    return _collectorSourceHash(collectorDirectory);
  }

  String _collectorSourceHash(Directory collectorDirectory) {
    final manifest = File('${collectorDirectory.path}/source_manifest.txt');
    if (!manifest.existsSync()) {
      throw const FormatException('Collector source manifest is missing.');
    }
    final listedPaths = manifest
        .readAsLinesSync()
        .map((value) => value.trim())
        .where((value) => value.isNotEmpty)
        .toList();
    final sortedPaths = listedPaths.toList()..sort();
    if (listedPaths.toSet().length != listedPaths.length ||
        !_listsEqual(listedPaths, sortedPaths) ||
        listedPaths.any(
          (path) =>
              path.startsWith('/') ||
              path.contains(r'\') ||
              path
                  .split('/')
                  .any(
                    (segment) => segment.isEmpty || segment == '.' || segment == '..',
                  ),
        )) {
      throw const FormatException(
        'Collector source manifest must contain unique, sorted, safe relative paths.',
      );
    }
    final isAndroid = collectorDirectory.path.endsWith('android_collector');
    final actualPaths =
        collectorDirectory
            .listSync(recursive: true, followLinks: false)
            .whereType<File>()
            .map(
              (file) => file.path.substring(collectorDirectory.path.length + 1).replaceAll(Platform.pathSeparator, '/'),
            )
            .where(
              (path) => isAndroid
                  ? path == 'source_manifest.txt' ||
                        path == 'build.gradle.kts' ||
                        path == 'settings.gradle.kts' ||
                        path == 'protocol.json' ||
                        path == 'app/build.gradle.kts' ||
                        path.startsWith('app/src/')
                  : path != 'collector_source_hash.h',
            )
            .toList()
          ..sort();
    final expectedPaths = <String>['source_manifest.txt', ...listedPaths]..sort();
    if (!_listsEqual(actualPaths, expectedPaths)) {
      throw const FormatException(
        'Collector source manifest does not match the canonical source tree.',
      );
    }
    final relativePaths = <String>['source_manifest.txt', ...listedPaths];
    final canonical = <int>[];
    for (final relative in relativePaths) {
      final file = File('${collectorDirectory.path}/$relative');
      if (!file.existsSync()) {
        throw FormatException(
          'Collector source manifest references missing file: $relative',
        );
      }
      canonical
        ..addAll(utf8.encode(relative))
        ..add(0)
        ..addAll(file.readAsBytesSync())
        ..add(0);
    }
    return DeviceDisplayModelEncoding.sha256Fingerprint(canonical);
  }

  bool _listsEqual(List<String> left, List<String> right) {
    if (left.length != right.length) {
      return false;
    }
    for (var index = 0; index < left.length; index += 1) {
      if (left[index] != right[index]) {
        return false;
      }
    }
    return true;
  }

  Future<bool> _apkContainsAndroidCollectorSource(
    String path,
    String sourceHash,
  ) async {
    final apkAnalyzer = _androidApkAnalyzerExecutable();
    if (apkAnalyzer == null) {
      return false;
    }
    const buildConfigClass = '$_androidCollectorPackage.BuildConfig';
    final dex = await _runBounded(apkAnalyzer, <String>[
      'dex',
      'code',
      '--class',
      buildConfigClass,
      path,
    ]);
    if (dex == null || dex.exitCode != 0) {
      return false;
    }
    final classDescriptor = buildConfigClass.replaceAll('.', '/');
    final declaresExpectedClass = RegExp(
      '^\\.class[^\\r\\n]*L${RegExp.escape(classDescriptor)};\\s*\$',
      multiLine: true,
    ).hasMatch(dex.stdout);
    final sourceHashFields = RegExp(
      r'^\.field public static final '
      r'COLLECTOR_SOURCE_HASH:Ljava/lang/String; = "([^"]+)"\s*$',
      multiLine: true,
    ).allMatches(dex.stdout).toList();
    return declaresExpectedClass && sourceHashFields.length == 1 && sourceHashFields.single.group(1) == sourceHash;
  }

  String? _androidApkAnalyzerExecutable() {
    final configured = Platform.environment['OMF_DEVICE_DISPLAY_APKANALYZER'];
    if (configured != null) {
      final executable = File(configured);
      final testCollectorAllowed = Platform.environment['OMF_DEVICE_DISPLAY_ALLOW_TEST_COLLECTOR'] == '1';
      return testCollectorAllowed && executable.isAbsolute && executable.existsSync() ? executable.path : null;
    }

    final sdkPath = Platform.environment['ANDROID_HOME'] ?? Platform.environment['ANDROID_SDK_ROOT'];
    if (sdkPath == null) {
      return 'apkanalyzer';
    }
    final executableName = Platform.isWindows ? 'apkanalyzer.bat' : 'apkanalyzer';
    final commandLineTools = Directory('$sdkPath/cmdline-tools');
    if (!commandLineTools.existsSync()) {
      return 'apkanalyzer';
    }
    final candidates =
        commandLineTools
            .listSync(followLinks: false)
            .whereType<Directory>()
            .map((directory) => File('${directory.path}/bin/$executableName'))
            .where((file) => file.existsSync())
            .toList()
          ..sort((left, right) => right.path.compareTo(left.path));
    final latest = File(
      '${commandLineTools.path}/latest/bin/$executableName',
    );
    if (latest.existsSync()) {
      return latest.path;
    }
    return candidates.isEmpty ? 'apkanalyzer' : candidates.first.path;
  }

