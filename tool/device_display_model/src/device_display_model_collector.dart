  Future<({int exitCode, String stdout, String stderr})?> _runBounded(
    String executable,
    List<String> arguments, {
    Duration? timeout,
  }) async {
    try {
      final process = await Process.start(executable, arguments);
      final stdoutBuffer = StringBuffer();
      final stderrBuffer = StringBuffer();
      final stdoutDone = Completer<void>();
      final stderrDone = Completer<void>();
      final stdoutSubscription =
          const Utf8Decoder(
                allowMalformed: true,
              )
              .bind(process.stdout)
              .listen(
                stdoutBuffer.write,
                onError: (_) => _complete(stdoutDone),
                onDone: () => _complete(stdoutDone),
              );
      final stderrSubscription =
          const Utf8Decoder(
                allowMalformed: true,
              )
              .bind(process.stderr)
              .listen(
                stderrBuffer.write,
                onError: (_) => _complete(stderrDone),
                onDone: () => _complete(stderrDone),
              );
      const grace = Duration(milliseconds: 500);
      final effectiveTimeout = timeout ?? _defaultProcessTimeout;
      int exitCode;
      try {
        exitCode = await process.exitCode.timeout(effectiveTimeout);
      } on TimeoutException {
        await _terminateProcess(process, grace: grace);
        await _finishProcessStream(
          stdoutSubscription,
          stdoutDone.future,
          grace: grace,
        );
        await _finishProcessStream(
          stderrSubscription,
          stderrDone.future,
          grace: grace,
        );
        return null;
      }
      final stdoutComplete = await _finishProcessStream(
        stdoutSubscription,
        stdoutDone.future,
        grace: grace,
      );
      final stderrComplete = await _finishProcessStream(
        stderrSubscription,
        stderrDone.future,
        grace: grace,
      );
      if (!stdoutComplete || !stderrComplete) {
        return null;
      }
      return (
        exitCode: exitCode,
        stdout: stdoutBuffer.toString(),
        stderr: stderrBuffer.toString(),
      );
    } on ProcessException {
      return null;
    }
  }

  Duration get _defaultProcessTimeout {
    if (Platform.environment['OMF_DEVICE_DISPLAY_ALLOW_TEST_COLLECTOR'] == '1') {
      final milliseconds = int.tryParse(
        Platform.environment['OMF_DEVICE_DISPLAY_PROCESS_TIMEOUT_MS'] ?? '',
      );
      if (milliseconds != null && milliseconds > 0) {
        return Duration(milliseconds: milliseconds);
      }
    }
    return const Duration(seconds: 15);
  }

  void _complete(Completer<void> completer) {
    if (!completer.isCompleted) {
      completer.complete();
    }
  }

  Future<void> _terminateProcess(
    Process process, {
    required Duration grace,
  }) async {
    if (Platform.isWindows) {
      final descendants = await _windowsDescendantProcessIds(
        process.pid,
        timeout: grace,
      );
      var taskkillSucceeded = false;
      try {
        final taskkill = await Process.run('taskkill', <String>[
          '/PID',
          '${process.pid}',
          '/T',
          '/F',
        ]).timeout(grace);
        taskkillSucceeded = taskkill.exitCode == 0;
      } on Object {
        taskkillSucceeded = false;
      }
      if (!taskkillSucceeded) {
        descendants.reversed.forEach(Process.killPid);
        process.kill();
      }
      try {
        await process.exitCode.timeout(grace);
      } on TimeoutException {
        process.kill();
      }
      return;
    }

    final descendants = await _descendantProcessIds(
      process.pid,
      timeout: grace,
    );
    process.kill(ProcessSignal.sigterm);
    for (final processId in descendants.reversed) {
      Process.killPid(processId, ProcessSignal.sigterm);
    }

    var parentExited = false;
    try {
      await process.exitCode.timeout(grace);
      parentExited = true;
    } on TimeoutException {
      // The hard-stop pass below handles a command that ignores termination.
    }
    for (final processId in descendants.reversed) {
      Process.killPid(processId, ProcessSignal.sigkill);
    }
    if (!parentExited) {
      process.kill(ProcessSignal.sigkill);
      try {
        await process.exitCode.timeout(grace);
      } on TimeoutException {
        return;
      }
    }
  }

  Future<List<int>> _descendantProcessIds(
    int parentProcessId, {
    required Duration timeout,
  }) async {
    try {
      final processTable = await Process.run(
        '/bin/ps',
        const <String>['-eo', 'pid=,ppid='],
      ).timeout(timeout);
      if (processTable.exitCode != 0) return const <int>[];
      return _descendantProcessIdsFromTable(
        processTable.stdout as String,
        parentProcessId,
      );
    } on Object {
      return const <int>[];
    }
  }

  Future<List<int>> _windowsDescendantProcessIds(
    int parentProcessId, {
    required Duration timeout,
  }) async {
    try {
      final processTable = await Process.run(
        'powershell.exe',
        const <String>[
          '-NoProfile',
          '-NonInteractive',
          '-Command',
          r'Get-CimInstance Win32_Process | ForEach-Object { "$($_.ProcessId) $($_.ParentProcessId)" }',
        ],
      ).timeout(timeout);
      if (processTable.exitCode != 0) return const <int>[];
      return _descendantProcessIdsFromTable(
        processTable.stdout as String,
        parentProcessId,
      );
    } on Object {
      return const <int>[];
    }
  }

  List<int> _descendantProcessIdsFromTable(
    String processTable,
    int parentProcessId,
  ) {
    final childrenByParent = <int, List<int>>{};
    for (final line in processTable.split('\n')) {
      final columns = line.trim().split(RegExp(r'\s+'));
      if (columns.length != 2) continue;

      final processId = int.tryParse(columns[0]);
      final parentId = int.tryParse(columns[1]);
      if (processId == null || parentId == null) continue;
      childrenByParent.putIfAbsent(parentId, () => <int>[]).add(processId);
    }

    final descendants = <int>[];
    final pendingParents = <int>[parentProcessId];
    while (pendingParents.isNotEmpty) {
      final children = childrenByParent[pendingParents.removeLast()];
      if (children == null) continue;
      descendants.addAll(children);
      pendingParents.addAll(children);
    }
    return descendants;
  }

  Future<bool> _finishProcessStream(
    StreamSubscription<String> subscription,
    Future<void> completed, {
    required Duration grace,
  }) async {
    try {
      await completed.timeout(grace);
      return true;
    } on TimeoutException {
      try {
        await subscription.cancel().timeout(grace);
      } on TimeoutException {
        // Cancellation is best effort after the bounded drain expires.
      }
      return false;
    }
  }

  Future<Map<String, Object?>> _collectApple({
    required String? iosDeviceAppPath,
  }) async {
    final deviceTypesResult = await _runXcrun(
      const ['simctl', 'list', 'devicetypes', '--json'],
    );
    final devicesResult = await _runXcrun(
      const ['simctl', 'list', 'devices', 'available', '--json'],
    );
    var deviceTypeCount = 0;
    var mobileDeviceTypeCount = 0;
    var framebufferMaskCount = 0;
    var framebufferCollisionCount = 0;
    var availableSimulatorCount = 0;
    var bootedSimulatorCount = 0;
    final chronologyRanksByProductType = <String, Set<int>>{};

    if (deviceTypesResult case final text?) {
      final root = jsonDecode(text) as Map<String, Object?>;
      final types = root['devicetypes']! as List<Object?>;
      deviceTypeCount = types.length;
      final masksByGeometry = <String, Set<String>>{};
      for (final value in types) {
        final type = value! as Map<String, Object?>;
        final family = type['productFamily'];
        if (family != 'iPhone' && family != 'iPad') {
          continue;
        }
        mobileDeviceTypeCount += 1;
        final bundlePath = type['bundlePath'];
        final profile = bundlePath is String
            ? await _readPlist(
                '$bundlePath/Contents/Resources/profile.plist',
              )
            : null;
        final modelIdentifier = type['modelIdentifier'] ?? profile?['modelIdentifier'];
        final minimumRuntimeVersion = type['minRuntimeVersion'];
        if (family == 'iPhone' &&
            modelIdentifier is String &&
            modelIdentifier.isNotEmpty &&
            minimumRuntimeVersion is int &&
            minimumRuntimeVersion >= 0) {
          chronologyRanksByProductType.putIfAbsent(modelIdentifier, () => <int>{}).add(minimumRuntimeVersion);
        }
        final mask = profile?['framebufferMask'];
        if (mask is! String || mask.isEmpty) {
          continue;
        }
        framebufferMaskCount += 1;
        final geometry = <String, Object?>{
          'width': profile?['mainScreenWidth'],
          'height': profile?['mainScreenHeight'],
          'scale': profile?['mainScreenScale'],
        };
        final signature = DeviceDisplayModelEncoding.fingerprint(geometry);
        masksByGeometry.putIfAbsent(signature, () => <String>{}).add(mask);
      }
      framebufferCollisionCount = masksByGeometry.values.where((masks) => masks.length > 1).length;
    }

    if (devicesResult case final text?) {
      final root = jsonDecode(text) as Map<String, Object?>;
      final runtimes = root['devices']! as Map<String, Object?>;
      for (final value in runtimes.values) {
        final devices = value! as List<Object?>;
        availableSimulatorCount += devices.length;
        for (final deviceValue in devices) {
          final device = deviceValue! as Map<String, Object?>;
          if (device['state'] == 'Booted') {
            bootedSimulatorCount += 1;
          }
        }
      }
    }

    final deviceTypeProvenanceByProductType = <String, ({String generationGroupHash, int chronologyRank})>{
      for (final entry in chronologyRanksByProductType.entries)
        if (entry.value.length == 1)
          entry.key: (
            generationGroupHash: DeviceDisplayModelEncoding.groupFingerprint(
              'generation-min-runtime:${entry.value.single}',
            ),
            chronologyRank: entry.value.single,
          ),
    };
    final connected = await _collectConnectedApple(
      iosDeviceAppPath: iosDeviceAppPath,
      deviceTypeProvenanceByProductType: deviceTypeProvenanceByProductType,
    );

    return <String, Object?>{
      'xcrunFound': deviceTypesResult != null,
      'deviceTypeCount': deviceTypeCount,
      'mobileDeviceTypeCount': mobileDeviceTypeCount,
      'framebufferMaskCount': framebufferMaskCount,
      'framebufferGeometryCollisionCount': framebufferCollisionCount,
      'availableSimulatorCount': availableSimulatorCount,
      'bootedSimulatorCount': bootedSimulatorCount,
      'exactLabelCount': 0,
      'maskLabelsUsedForTraining': false,
      'connectedDeviceCount': connected.deviceCount,
      'connectedEligibleDeviceCount': connected.eligibleDeviceCount,
      'connectedCollectorAppSupplied': iosDeviceAppPath != null,
      'connectedCollectorAttemptCount': connected.attemptedDeviceCount,
      'connectedLabelCount': connected.records.length,
      'connectedCollectorFailureCount': connected.failureCount,
      'connectedCollectorSourceHash': connected.collectorSourceHash,
      'connectedRecords': connected.records,
    };
  }

  Future<
    ({
      int deviceCount,
      int eligibleDeviceCount,
      int attemptedDeviceCount,
      int failureCount,
      String? collectorSourceHash,
      List<Map<String, Object?>> records,
    })
  >
  _collectConnectedApple({
    required String? iosDeviceAppPath,
    required Map<String, ({String generationGroupHash, int chronologyRank})> deviceTypeProvenanceByProductType,
  }) async {
    final temporaryDirectory = Directory.systemTemp.createTempSync(
      'omf-device-display-ios-',
    );
    final permissions = await _runBounded(
      'chmod',
      <String>['700', temporaryDirectory.path],
    );
    if (permissions?.exitCode != 0) {
      temporaryDirectory.deleteSync(recursive: true);
      return (
        deviceCount: 0,
        eligibleDeviceCount: 0,
        attemptedDeviceCount: 0,
        failureCount: 1,
        collectorSourceHash: null,
        records: <Map<String, Object?>>[],
      );
    }
    try {
      final inventory = await _runDevicectlJson(
        const <String>['list', 'devices'],
        temporaryDirectory: temporaryDirectory,
        outputName: 'inventory',
      );
      final values = inventory?['result'] is Map<String, Object?>
          ? ((inventory!['result']! as Map<String, Object?>)['devices'] as List<Object?>? ?? const <Object?>[])
          : const <Object?>[];
      final devices = <Map<String, Object?>>[];
      for (final value in values) {
        if (value is! Map<String, Object?>) {
          continue;
        }
        final hardware = value['hardwareProperties'];
        if (hardware is! Map<String, Object?>) {
          continue;
        }
        final platform = (hardware['platform'] as String?)?.toLowerCase();
        final reality = (hardware['reality'] as String?)?.toLowerCase();
        final productType = hardware['productType'] as String?;
        if (platform == 'ios' && reality == 'physical' && productType?.startsWith('iPhone') == true) {
          devices.add(value);
        }
      }
      final eligible = devices.where(_isEligibleConnectedAppleDevice).toList();
      if (iosDeviceAppPath == null) {
        return (
          deviceCount: devices.length,
          eligibleDeviceCount: eligible.length,
          attemptedDeviceCount: 0,
          failureCount: 0,
          collectorSourceHash: null,
          records: <Map<String, Object?>>[],
        );
      }
      final app = await _validatedIosDeviceApp(iosDeviceAppPath);
      if (app == null) {
        return (
          deviceCount: devices.length,
          eligibleDeviceCount: eligible.length,
          attemptedDeviceCount: 0,
          failureCount: eligible.length,
          collectorSourceHash: null,
          records: <Map<String, Object?>>[],
        );
      }

      final records = <Map<String, Object?>>[];
      var failureCount = 0;
      for (var index = 0; index < eligible.length; index += 1) {
        final device = eligible[index];
        final identifier = device['identifier'];
        if (identifier is! String || identifier.isEmpty) {
          failureCount += 1;
          continue;
        }
        final hardware = device['hardwareProperties']! as Map<String, Object?>;
        final deviceUdid = hardware['udid'];
        if (!app.provisionsAllDevices &&
            (deviceUdid is! String || !app.provisionedDeviceIdentifiers.contains(deviceUdid))) {
          failureCount += 1;
          continue;
        }
        final nonce = base64Url.encode(
          List<int>.generate(24, (_) => math.Random.secure().nextInt(256)),
        );
        var installAttempted = false;
        try {
          installAttempted = true;
          final install = await _runDevicectlJson(
            <String>[
              'device',
              'install',
              'app',
              '--device',
              identifier,
              app.path,
            ],
            temporaryDirectory: temporaryDirectory,
            outputName: 'install-$index',
          );
          if (install == null) {
            failureCount += 1;
            continue;
          }
          final launch = await _runDevicectlJson(
            <String>[
              'device',
              'process',
              'launch',
              '--device',
              identifier,
              '--terminate-existing',
              '--environment-variables',
              jsonEncode(<String, String>{
                'OMF_DEVICE_DISPLAY_COLLECTOR_NONCE': nonce,
              }),
              app.bundleIdentifier,
            ],
            temporaryDirectory: temporaryDirectory,
            outputName: 'launch-$index',
          );
          if (launch == null) {
            failureCount += 1;
            continue;
          }
          Map<String, Object?>? payload;
          for (var attempt = 0; attempt < 10; attempt += 1) {
            final destination = Directory(
              '${temporaryDirectory.path}/copy-$index-$attempt',
            )..createSync();
            final copied = await _runDevicectlJson(
              <String>[
                'device',
                'copy',
                'from',
                '--device',
                identifier,
                '--source',
                'Documents/record.json',
                '--destination',
                destination.path,
                '--domain-type',
                'appDataContainer',
                '--domain-identifier',
                app.bundleIdentifier,
              ],
              temporaryDirectory: temporaryDirectory,
              outputName: 'copy-$index-$attempt',
            );
            if (copied != null) {
              final files = destination
                  .listSync(recursive: true)
                  .whereType<File>()
                  .where((file) => file.path.endsWith('record.json'))
                  .toList();
              if (files.length == 1) {
                try {
                  payload = jsonDecode(files.single.readAsStringSync()) as Map<String, Object?>;
                } on FormatException {
                  payload = null;
                }
              }
            }
            if (payload?['nonce'] == nonce) {
              break;
            }
            payload = null;
            await Future<void>.delayed(const Duration(milliseconds: 500));
          }
          final record = payload == null
              ? null
              : _importConnectedIosRecord(
                  payload,
                  expectedNonce: nonce,
                  expectedSourceHash: app.sourceHash,
                  device: device,
                  deviceTypeProvenanceByProductType: deviceTypeProvenanceByProductType,
                );
          if (record == null) {
            failureCount += 1;
          } else {
            records.add(record);
          }
        } finally {
          if (installAttempted) {
            await _runDevicectlJson(
              <String>[
                'device',
                'uninstall',
                'app',
                '--device',
                identifier,
                app.bundleIdentifier,
              ],
              temporaryDirectory: temporaryDirectory,
              outputName: 'uninstall-$index',
            );
          }
        }
      }
      return (
        deviceCount: devices.length,
        eligibleDeviceCount: eligible.length,
        attemptedDeviceCount: eligible.length,
        failureCount: failureCount,
        collectorSourceHash: app.sourceHash,
        records: records,
      );
    } finally {
      temporaryDirectory.deleteSync(recursive: true);
    }
  }

  bool _isEligibleConnectedAppleDevice(Map<String, Object?> device) {
    final properties = device['deviceProperties'];
    final connection = device['connectionProperties'];
    if (properties is! Map<String, Object?> || connection is! Map<String, Object?>) {
      return false;
    }
    final version = properties['osVersionNumber'] as String?;
    final major = int.tryParse(version?.split('.').first ?? '');
    final pairing = (connection['pairingState'] as String?)?.toLowerCase();
    final developerMode = (properties['developerModeStatus'] as String?)?.toLowerCase();
    final bootState = (properties['bootState'] as String?)?.toLowerCase();
    final transport = (connection['transportType'] as String?)?.toLowerCase();
    final tunnelState = (connection['tunnelState'] as String?)?.toLowerCase();
    final allowNetwork = Platform.environment['OMF_DEVICE_DISPLAY_ALLOW_NETWORK_IOS_DEVICES'] == '1';
    return major != null &&
        major >= 26 &&
        pairing != null &&
        pairing.contains('paired') &&
        !pairing.contains('unpaired') &&
        developerMode == 'enabled' &&
        properties['ddiServicesAvailable'] == true &&
        bootState == 'booted' &&
        tunnelState == 'connected' &&
        (transport == 'wired' || (allowNetwork && transport == 'localnetwork'));
  }

  Future<
    ({
      String path,
      String bundleIdentifier,
      String sourceHash,
      bool provisionsAllDevices,
      Set<String> provisionedDeviceIdentifiers,
    })?
  >
  _validatedIosDeviceApp(String rawPath) async {
    final directory = Directory(rawPath);
    if (!directory.isAbsolute || !directory.path.endsWith('.app') || !directory.existsSync()) {
      return null;
    }
    final info = await _readPlist('${directory.path}/Info.plist');
    final bundleIdentifier = info?['CFBundleIdentifier'];
    final executableName = info?['CFBundleExecutable'];
    final minimumVersion = info?['MinimumOSVersion'];
    if (bundleIdentifier is! String ||
        bundleIdentifier.isEmpty ||
        executableName is! String ||
        executableName.isEmpty ||
        minimumVersion is! String ||
        (int.tryParse(minimumVersion.split('.').first) ?? 0) < 26) {
      return null;
    }
    final executable = File('${directory.path}/$executableName');
    final profile = File('${directory.path}/embedded.mobileprovision');
    if (!executable.existsSync() || !profile.existsSync()) {
      return null;
    }
    final collectorDirectory = Directory(
      '${Directory.current.path}/tool/device_display_model/ios_device_collector',
    );
    final sourceHash = _collectorSourceHash(collectorDirectory);
    final generatedHeader = File(
      '${collectorDirectory.path}/collector_source_hash.h',
    );
    final expectedHeader =
        '// Generated by generate_ios_device_collector_provenance.sh.\n'
        '#define OMF_DEVICE_DISPLAY_COLLECTOR_SOURCE_HASH @"$sourceHash"\n';
    if (!generatedHeader.existsSync() || generatedHeader.readAsStringSync() != expectedHeader) {
      return null;
    }
    final forbidden = RegExp(
      'NSSelectorFromString|_displayCornerRadius|legacyDisplayCornerRadius',
      caseSensitive: false,
    );
    final executableText = utf8.decode(
      executable.readAsBytesSync(),
      allowMalformed: true,
    );
    if (!executableText.contains(sourceHash)) {
      return null;
    }
    for (final entity in directory.listSync(recursive: true).whereType<File>()) {
      final text = utf8.decode(entity.readAsBytesSync(), allowMalformed: true);
      if (forbidden.hasMatch(text)) {
        return null;
      }
    }
    final signature = await _runBounded(
      'codesign',
      <String>['--verify', '--deep', '--strict', directory.path],
    );
    final provisioning = await _runBounded(
      'security',
      <String>['cms', '-D', '-i', profile.path],
    );
    if (signature?.exitCode != 0 || provisioning?.exitCode != 0 || provisioning!.stdout.isEmpty) {
      return null;
    }
    final applicationIdentifier = RegExp(
      r'<key>application-identifier</key>\s*<string>([^<]+)</string>',
      dotAll: true,
    ).firstMatch(provisioning.stdout)?.group(1);
    if (applicationIdentifier == null || !applicationIdentifier.endsWith('.$bundleIdentifier')) {
      return null;
    }
    final provisionsAllDevices = RegExp(
      r'<key>ProvisionsAllDevices</key>\s*<true\s*/>',
      dotAll: true,
    ).hasMatch(provisioning.stdout);
    final devicesBlock = RegExp(
      r'<key>ProvisionedDevices</key>\s*<array>(.*?)</array>',
      dotAll: true,
    ).firstMatch(provisioning.stdout)?.group(1);
    final provisionedDeviceIdentifiers = <String>{
      if (devicesBlock != null)
        for (final match in RegExp('<string>([^<]+)</string>').allMatches(devicesBlock)) match.group(1)!,
    };
    if (!provisionsAllDevices && provisionedDeviceIdentifiers.isEmpty) {
      return null;
    }
    return (
      path: directory.path,
      bundleIdentifier: bundleIdentifier,
      sourceHash: sourceHash,
      provisionsAllDevices: provisionsAllDevices,
      provisionedDeviceIdentifiers: provisionedDeviceIdentifiers,
    );
  }

  Future<Map<String, Object?>?> _runDevicectlJson(
    List<String> arguments, {
    required Directory temporaryDirectory,
    required String outputName,
  }) async {
    final output = File('${temporaryDirectory.path}/$outputName.json');
    final executable = Platform.environment['OMF_DEVICE_DISPLAY_DEVICETL'] ?? 'xcrun';
    final prefix = Platform.environment['OMF_DEVICE_DISPLAY_DEVICETL'] == null
        ? const <String>['devicectl']
        : const <String>[];
    final result = await _runBounded(
      executable,
      <String>[
        ...prefix,
        ...arguments,
        '--timeout',
        '30',
        '--json-output',
        output.path,
        '--quiet',
      ],
      timeout: const Duration(seconds: 40),
    );
    if (result == null || result.exitCode != 0 || !output.existsSync()) {
      return null;
    }
    try {
      final decoded = jsonDecode(output.readAsStringSync()) as Map<String, Object?>;
      final info = decoded['info'];
      if (info is! Map<String, Object?> || info['outcome'] != 'success' || info['jsonVersion'] != 3) {
        return null;
      }
      return decoded;
    } on FormatException {
      return null;
    }
  }

  Map<String, Object?>? _importConnectedIosRecord(
    Map<String, Object?> payload, {
    required String expectedNonce,
    required String expectedSourceHash,
    required Map<String, Object?> device,
    required Map<String, ({String generationGroupHash, int chronologyRank})> deviceTypeProvenanceByProductType,
  }) {
    if (payload['protocolVersion'] != 1 ||
        payload['protocolSourceHash'] != expectedSourceHash ||
        payload['platform'] != 'ios' ||
        payload['sourceKind'] != 'ios26_connected_public_uikit_concentric_corner' ||
        payload['nonce'] != expectedNonce) {
      return null;
    }
    const positiveKeys = <String>[
      'physicalWidth',
      'physicalHeight',
      'viewPhysicalWidth',
      'viewPhysicalHeight',
      'devicePixelRatio',
    ];
    const nonNegativeKeys = <String>[
      'viewPaddingLeftPhysical',
      'viewPaddingTopPhysical',
      'viewPaddingRightPhysical',
      'viewPaddingBottomPhysical',
      'topLeftRadiusPhysical',
      'topRightRadiusPhysical',
      'bottomRightRadiusPhysical',
      'bottomLeftRadiusPhysical',
    ];
    if (positiveKeys.any(
          (key) => !_isFiniteNumber(payload[key], positive: true),
        ) ||
        nonNegativeKeys.any(
          (key) => !_isFiniteNumber(payload[key], positive: false),
        )) {
      return null;
    }
    final width = (payload['physicalWidth']! as num).toDouble();
    final height = (payload['physicalHeight']! as num).toDouble();
    final density = (payload['devicePixelRatio']! as num).toDouble();
    final viewWidth = (payload['viewPhysicalWidth']! as num).toDouble();
    final viewHeight = (payload['viewPhysicalHeight']! as num).toDouble();
    final radii = <double>[
      for (final key in const <String>[
        'topLeftRadiusPhysical',
        'topRightRadiusPhysical',
        'bottomRightRadiusPhysical',
        'bottomLeftRadiusPhysical',
      ])
        (payload[key]! as num).toDouble(),
    ];
    if (!_hasPhoneGeometry(
          physicalWidth: width,
          physicalHeight: height,
          devicePixelRatio: density,
        ) ||
        width > height ||
        viewWidth > width ||
        viewHeight > height ||
        radii.any((radius) => radius > math.min(width, height) / 2)) {
      return null;
    }
    final hardware = device['hardwareProperties']! as Map<String, Object?>;
    final familySeed = hardware['productType'] as String?;
    final deviceTypeProvenance = familySeed == null ? null : deviceTypeProvenanceByProductType[familySeed];
    final isSquare = radii.every((radius) => radius == 0);
    return _record(
      platform: 'ios',
      sourceKind: 'ios26_connected_public_uikit_concentric_corner',
      physicalWidth: width,
      physicalHeight: height,
      viewPhysicalWidth: viewWidth,
      viewPhysicalHeight: viewHeight,
      devicePixelRatio: density,
      viewPaddingLeftPhysical: payload['viewPaddingLeftPhysical']! as num,
      viewPaddingTopPhysical: payload['viewPaddingTopPhysical']! as num,
      viewPaddingRightPhysical: payload['viewPaddingRightPhysical']! as num,
      viewPaddingBottomPhysical: payload['viewPaddingBottomPhysical']! as num,
      topRadiusPhysical: (radii[0] + radii[1]) / 2,
      bottomRadiusPhysical: (radii[2] + radii[3]) / 2,
      provenance: <String, Object?>{
        if (familySeed != null)
          'familyGroupHash': DeviceDisplayModelEncoding.groupFingerprint(
            'family-product:$familySeed',
          ),
        if (deviceTypeProvenance != null) ...<String, Object?>{
          'generationGroupHash': deviceTypeProvenance.generationGroupHash,
          'chronologyRank': deviceTypeProvenance.chronologyRank,
        },
        'oemGroupHash': DeviceDisplayModelEncoding.groupFingerprint(
          'oem:apple',
        ),
      },
      labelAuthority: 'ios26_connected_public_uikit_concentric_corner',
      cornerClassification: isSquare ? 'square' : 'rounded',
    );
  }

  Future<String?> _runXcrun(List<String> arguments) async {
    final configured = Platform.environment['OMF_DEVICE_DISPLAY_XCRUN'];
    final testCollectorAllowed = Platform.environment['OMF_DEVICE_DISPLAY_ALLOW_TEST_COLLECTOR'] == '1';
    final configuredFile = configured == null ? null : File(configured);
    final executable =
        testCollectorAllowed && configuredFile != null && configuredFile.isAbsolute && configuredFile.existsSync()
        ? configuredFile.path
        : 'xcrun';
    final result = await _runBounded(
      executable,
      arguments,
      timeout: const Duration(seconds: 30),
    );
    return result?.exitCode == 0 ? result!.stdout : null;
  }

  Future<Map<String, Object?>?> _readPlist(String path) async {
    if (!File(path).existsSync()) {
      return null;
    }
    final result = await _runBounded(
      'plutil',
      ['-convert', 'json', '-o', '-', path],
    );
    if (result == null || result.exitCode != 0) {
      return null;
    }
    return jsonDecode(result.stdout) as Map<String, Object?>;
  }

  Map<String, Object?> _record({
    required String sourceKind,
    required num physicalWidth,
    required num physicalHeight,
    required num? devicePixelRatio,
    required num? viewPaddingTopPhysical,
    required num? viewPaddingBottomPhysical,
    required num topRadiusPhysical,
    required num bottomRadiusPhysical,
    String platform = 'android',
    Map<String, Object?> provenance = const <String, Object?>{},
    int? sourceApiLevel,
    String? labelAuthority,
    String? cornerClassification,
    num? viewPhysicalWidth,
    num? viewPhysicalHeight,
    num? viewPaddingLeftPhysical,
    num? viewPaddingRightPhysical,
    num? systemGestureInsetLeftPhysical,
    num? systemGestureInsetTopPhysical,
    num? systemGestureInsetRightPhysical,
    num? systemGestureInsetBottomPhysical,
    num? displayCutoutWidthPhysical,
    num? displayCutoutHeightPhysical,
    num? displayCutoutCount,
  }) {
    final geometry = <String, Object?>{
      'physicalWidth': physicalWidth,
      'physicalHeight': physicalHeight,
    };
    final geometryHash = DeviceDisplayModelEncoding.fingerprint(geometry);
    final record = <String, Object?>{
      'platform': platform,
      'sourceKind': sourceKind,
      'validationGroup': geometryHash,
      'geometryCollisionGroupHash': geometryHash,
      ...geometry,
      'viewPhysicalWidth': viewPhysicalWidth,
      'viewPhysicalHeight': viewPhysicalHeight,
      'devicePixelRatio': devicePixelRatio,
      'viewPaddingLeftPhysical': viewPaddingLeftPhysical,
      'viewPaddingTopPhysical': viewPaddingTopPhysical,
      'viewPaddingRightPhysical': viewPaddingRightPhysical,
      'viewPaddingBottomPhysical': viewPaddingBottomPhysical,
      'systemGestureInsetLeftPhysical': systemGestureInsetLeftPhysical,
      'systemGestureInsetTopPhysical': systemGestureInsetTopPhysical,
      'systemGestureInsetRightPhysical': systemGestureInsetRightPhysical,
      'systemGestureInsetBottomPhysical': systemGestureInsetBottomPhysical,
      'displayCutoutWidthPhysical': displayCutoutWidthPhysical,
      'displayCutoutHeightPhysical': displayCutoutHeightPhysical,
      'displayCutoutCount': displayCutoutCount,
      'topRadiusPhysical': topRadiusPhysical,
      'bottomRadiusPhysical': bottomRadiusPhysical,
      'sourceApiLevel': sourceApiLevel,
      'labelAuthority': labelAuthority,
      'cornerClassification': cornerClassification,
      ...provenance,
    };
    record['observableCollisionGroupHash'] = DeviceDisplayModelEncoding.fingerprint(<String, Object?>{
      'platform': platform,
      'features': _DeviceDisplayModelAlgorithms().features(record),
    });
    record['familyGroupHash'] ??= geometryHash;
    record.putIfAbsent('chronologyRank', () => null);
    _updateSourceObservationHash(record);
    return record;
  }

  void _updateSourceObservationHash(Map<String, Object?> record) {
    record['sourceObservationHash'] = DeviceDisplayModelEncoding.fingerprint(
      <String, Object?>{
        for (final entry in record.entries)
          if (entry.key != 'maskCollisionGroupHash' && entry.key != 'sourceObservationHash') entry.key: entry.value,
      },
    );
  }

  Map<String, Object?> _anonymousProvenance(String rawValue) {
    return <String, Object?>{
      'familyGroupHash': _hashGroup(
        'family',
        rawValue.trim().toLowerCase(),
      ),
    };
  }

  Future<Map<String, Object?>> _connectedAndroidProvenance(
    String adbPath,
    String serial,
  ) async {
    final values = <String>[];
    for (final property in const [
      'ro.product.manufacturer',
      'ro.product.model',
      'ro.product.device',
    ]) {
      final result = await _runBounded(adbPath, <String>[
        '-s',
        serial,
        'shell',
        'getprop',
        property,
      ]);
      values.add(result?.exitCode == 0 ? result!.stdout.trim() : '');
    }
    final family = values.skip(1).where((value) => value.isNotEmpty).join('-');
    final manufacturer = values.first.toLowerCase();
    return <String, Object?>{
      if (family.isNotEmpty) 'familyGroupHash': _hashGroup('family', family.toLowerCase()),
      if (manufacturer.isNotEmpty) 'oemGroupHash': _hashGroup('oem', manufacturer),
    };
  }

  String _hashGroup(String category, String value) => DeviceDisplayModelEncoding.groupFingerprint('$category:$value');

  int? _integer(String text, String key) {
    final match = RegExp('$key\\s+(\\d+)').firstMatch(text);
    return match == null ? null : int.parse(match.group(1)!);
  }

  static int _compareRecords(
    Map<String, Object?> left,
    Map<String, Object?> right,
  ) => DeviceDisplayModelEncoding.canonicalJson(
    left,
  ).compareTo(DeviceDisplayModelEncoding.canonicalJson(right));
