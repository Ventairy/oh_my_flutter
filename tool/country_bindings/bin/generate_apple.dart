import 'dart:io';

import 'package:ffigen/ffigen.dart';

void main(List<String> arguments) {
  if (!Platform.isMacOS) {
    throw UnsupportedError('Apple binding generation requires Xcode on macOS.');
  }
  final sdk = Process.runSync('xcrun', ['--sdk', 'macosx', '--show-sdk-path']);
  if (sdk.exitCode != 0) throw ProcessException('xcrun', [], '${sdk.stderr}', sdk.exitCode);
  final sdkPath = (sdk.stdout as String).trim();
  final output = arguments.isEmpty
      ? Platform.script.resolve('../../../lib/src/gen/country_names_apple.g.dart')
      : File(arguments.single).absolute.uri;
  FfiGenerator(
    headers: Headers(
      entryPoints: [
        Uri.file('$sdkPath/System/Library/Frameworks/CoreFoundation.framework/Headers/CFLocale.h'),
        Uri.file('$sdkPath/System/Library/Frameworks/CoreFoundation.framework/Headers/CFString.h'),
      ],
      include: (header) => {'CFBase.h', 'CFLocale.h', 'CFString.h'}.contains(header.pathSegments.last),
      compilerOptions: ['-isysroot', sdkPath],
    ),
    functions: Functions.includeSet({
      'CFStringCreateWithBytes',
      'CFLocaleCreate',
      'CFLocaleCopyDisplayNameForPropertyValue',
      'CFStringGetLength',
      'CFStringGetCString',
      'CFRelease',
    }),
    globals: Globals.includeSet({'kCFLocaleCountryCode'}),
    structs: Structs(
      rename: (declaration) => switch (declaration.originalName) {
        '__CFLocale' => 'CountryNamesAppleLocale',
        '__CFAllocator' => 'CountryNamesAppleAllocator',
        _ => declaration.originalName,
      },
    ),
    output: Output(
      dartFile: output,
      style: const DynamicLibraryBindings(wrapperName: 'CountryNamesAppleBindings'),
      commentType: const CommentType(CommentStyle.doxygen, CommentLength.brief),
      preamble: '// Generated by tool/country_bindings/bin/generate_apple.dart. Do not edit.',
    ),
  ).generate();
}
