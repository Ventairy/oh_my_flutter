import 'dart:io';

import 'package:jnigen/jnigen.dart';

Future<void> main(List<String> arguments) async {
  final root = Platform.script.resolve('../../../');
  await JniGenerator(
    input: Input(
      classes: ['dev.ventairy.oh_my_flutter.CountryNamesBridge'],
      classPath: [
        root.resolve(
          'example/build/oh_my_flutter/intermediates/built_in_kotlinc/release/compileReleaseKotlin/classes/',
        ),
      ],
      backend: SummarizerBackend.asm,
    ),
    output: Output(
      dart: DartOutput(
        path: arguments.isEmpty
            ? root.resolve('lib/src/gen/country_names_android.g.dart')
            : File(arguments.single).absolute.uri,
        structure: OutputStructure.singleFile,
      ),
      preamble: '// Generated by tool/country_bindings/bin/generate_android.dart. Do not edit.',
    ),
    visitors: [
      Visitor(
        field: (field) => field.isIncluded = false,
        method: (method) => method.isIncluded = method.name == 'displayName',
      ),
    ],
  ).generate();
}
