part of 'interactive_swipe_dismiss.dart';

/// The physical direction in which an interactive dismissal progresses.
enum InteractiveSwipeDismissDirection {
  /// Progresses from the top of the view toward the bottom.
  down,

  /// Progresses from the bottom of the view toward the top.
  up,

  /// Progresses from the right of the view toward the left.
  left,

  /// Progresses from the left of the view toward the right.
  right,
}
