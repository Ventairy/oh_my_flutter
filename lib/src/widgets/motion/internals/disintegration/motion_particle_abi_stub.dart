import 'dart:typed_data';

/// Identifies the particle arithmetic target when Dart FFI is unavailable.
abstract final class MotionParticleAbi {
  /// Whether this target uses Android's little-endian ARM32 ABI.
  static const isAndroidArm32 = false;

  /// Whether both ARM32 frozen particle kernels are available.
  static const canWriteFrozenPose = false;

  /// The web fallback keeps the Dart writer.
  static int fillNativeFirstPose(
    int columns,
    int rows,
    int curlColumns,
    int firstParticle,
    int seed,
    int moves,
    int sampleCount,
    int firstDormantColumn,
    double width,
    double progress,
    double directionCosine,
    double directionSine,
    double pivotX,
    double pivotY,
    double suffixCosine,
    double suffixSine,
    double suffixX,
    double suffixY,
    double spriteScale,
    double suffixAlpha,
    Float64List motion,
    Float32List samples,
    Float64List columnCenters,
    Float64List rowCenters,
    Float64List tileCentersX,
    Float64List tileCentersY,
    Float64List tileWidths,
    Float64List tileHeights,
    Float32List delays,
    Float32List lifetimes,
    Float32List xDrifts,
    Float32List yDrifts,
    Float64List curlSines,
    Float64List curlCosines,
    Float64List scales,
    Float64List opacities,
    Float64List offsetsX,
    Float64List offsetsY,
    Float32List horizontalEdges,
    Float32List verticalEdges,
    Float32List transforms,
    Float32List rects,
    Int32List colors,
  ) => throw UnsupportedError('Native ARMv7 particles are unavailable.');

  /// The web fallback keeps the Dart path.
  static int fillNativeTerminalPose(
    int columns,
    int rows,
    int oldCurlColumns,
    int curlColumns,
    int firstParticle,
    int moves,
    int sampleCount,
    int firstDormantColumn,
    int omitZero,
    int updatePose,
    double progress,
    double directionCosine,
    double directionSine,
    double pivotX,
    double pivotY,
    double suffixCosine,
    double suffixSine,
    double suffixX,
    double suffixY,
    double spriteScale,
    double suffixAlpha,
    Float32List samples,
    Float64List columnCenters,
    Float64List rowCenters,
    Float64List tileCentersX,
    Float64List tileCentersY,
    Float64List tileWidths,
    Float64List tileHeights,
    Float32List delays,
    Float32List lifetimes,
    Float32List xDrifts,
    Float32List yDrifts,
    Float64List curlSines,
    Float64List curlCosines,
    Float64List scales,
    Float64List opacities,
    Float64List offsetsX,
    Float64List offsetsY,
    Float32List horizontalEdges,
    Float32List verticalEdges,
    Float32List transforms,
    Float32List rects,
    Int32List colors,
  ) => throw UnsupportedError('Native ARMv7 particles are unavailable.');
}
