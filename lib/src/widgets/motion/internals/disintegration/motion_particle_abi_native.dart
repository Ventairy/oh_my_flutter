import 'dart:ffi';
import 'dart:typed_data';

/// Identifies the native ABI used for particle arithmetic.
abstract final class MotionParticleAbi {
  /// Whether this target uses Android's little-endian ARM32 ABI.
  static bool get isAndroidArm32 => Abi.current() == Abi.androidArm;

  /// Whether both ARM32 frozen particle kernels are available.
  static final bool canWriteFrozenPose = _resolveFrozenPose();

  static bool _resolveFrozenPose() {
    if (!isAndroidArm32) return false;
    try {
      return Native.addressOf<NativeFunction<_FirstPoseSignature>>(_firstPose) != nullptr &&
          Native.addressOf<NativeFunction<_TerminalPoseSignature>>(_terminalPose) != nullptr;
    } catch (error) {
      if (error is! ArgumentError) rethrow;
      return false;
    }
  }

  /// Writes a frozen pose into the Dart-owned buffers.
  static int fillNativeFirstPose(
    int columns,
    int rows,
    int curlColumns,
    int firstParticle,
    int seed,
    int moves,
    int sampleCount,
    int firstDormantColumn,
    double width,
    double progress,
    double directionCosine,
    double directionSine,
    double pivotX,
    double pivotY,
    double suffixCosine,
    double suffixSine,
    double suffixX,
    double suffixY,
    double spriteScale,
    double suffixAlpha,
    Float64List motion,
    Float32List samples,
    Float64List columnCenters,
    Float64List rowCenters,
    Float64List tileCentersX,
    Float64List tileCentersY,
    Float64List tileWidths,
    Float64List tileHeights,
    Float32List delays,
    Float32List lifetimes,
    Float32List xDrifts,
    Float32List yDrifts,
    Float64List curlSines,
    Float64List curlCosines,
    Float64List scales,
    Float64List opacities,
    Float64List offsetsX,
    Float64List offsetsY,
    Float32List horizontalEdges,
    Float32List verticalEdges,
    Float32List transforms,
    Float32List rects,
    Int32List colors,
  ) {
    return _firstPose(
      columns,
      rows,
      curlColumns,
      firstParticle,
      seed,
      moves,
      sampleCount,
      firstDormantColumn,
      width,
      progress,
      directionCosine,
      directionSine,
      pivotX,
      pivotY,
      suffixCosine,
      suffixSine,
      suffixX,
      suffixY,
      spriteScale,
      suffixAlpha,
      motion.address,
      samples.address,
      columnCenters.address,
      rowCenters.address,
      tileCentersX.address,
      tileCentersY.address,
      tileWidths.address,
      tileHeights.address,
      delays.address,
      lifetimes.address,
      xDrifts.address,
      yDrifts.address,
      curlSines.address,
      curlCosines.address,
      scales.address,
      opacities.address,
      offsetsX.address,
      offsetsY.address,
      horizontalEdges.address,
      verticalEdges.address,
      transforms.address,
      rects.address,
      colors.address,
    );
  }

  /// Updates retained particle pose and atlas buffers without copying them.
  static int fillNativeTerminalPose(
    int columns,
    int rows,
    int oldCurlColumns,
    int curlColumns,
    int firstParticle,
    int moves,
    int sampleCount,
    int firstDormantColumn,
    int omitZero,
    int updatePose,
    double progress,
    double directionCosine,
    double directionSine,
    double pivotX,
    double pivotY,
    double suffixCosine,
    double suffixSine,
    double suffixX,
    double suffixY,
    double spriteScale,
    double suffixAlpha,
    Float32List samples,
    Float64List columnCenters,
    Float64List rowCenters,
    Float64List tileCentersX,
    Float64List tileCentersY,
    Float64List tileWidths,
    Float64List tileHeights,
    Float32List delays,
    Float32List lifetimes,
    Float32List xDrifts,
    Float32List yDrifts,
    Float64List curlSines,
    Float64List curlCosines,
    Float64List scales,
    Float64List opacities,
    Float64List offsetsX,
    Float64List offsetsY,
    Float32List horizontalEdges,
    Float32List verticalEdges,
    Float32List transforms,
    Float32List rects,
    Int32List colors,
  ) {
    return _terminalPose(
      columns,
      rows,
      oldCurlColumns,
      curlColumns,
      firstParticle,
      moves,
      sampleCount,
      firstDormantColumn,
      omitZero,
      updatePose,
      progress,
      directionCosine,
      directionSine,
      pivotX,
      pivotY,
      suffixCosine,
      suffixSine,
      suffixX,
      suffixY,
      spriteScale,
      suffixAlpha,
      samples.address,
      columnCenters.address,
      rowCenters.address,
      tileCentersX.address,
      tileCentersY.address,
      tileWidths.address,
      tileHeights.address,
      delays.address,
      lifetimes.address,
      xDrifts.address,
      yDrifts.address,
      curlSines.address,
      curlCosines.address,
      scales.address,
      opacities.address,
      offsetsX.address,
      offsetsY.address,
      horizontalEdges.address,
      verticalEdges.address,
      transforms.address,
      rects.address,
      colors.address,
    );
  }

  @Native<_FirstPoseSignature>(
    isLeaf: true,
    symbol: 'omf_motion_first_pose',
    assetId: 'package:oh_my_flutter/src/widgets/motion/internals/disintegration/motion_particle_abi_native.dart',
  )
  external static int _firstPose(
    int columns,
    int rows,
    int curlColumns,
    int firstParticle,
    int seed,
    int moves,
    int sampleCount,
    int firstDormantColumn,
    double width,
    double progress,
    double directionCosine,
    double directionSine,
    double pivotX,
    double pivotY,
    double suffixCosine,
    double suffixSine,
    double suffixX,
    double suffixY,
    double spriteScale,
    double suffixAlpha,
    Pointer<Double> motion,
    Pointer<Float> samples,
    Pointer<Double> columnCenters,
    Pointer<Double> rowCenters,
    Pointer<Double> tileCentersX,
    Pointer<Double> tileCentersY,
    Pointer<Double> tileWidths,
    Pointer<Double> tileHeights,
    Pointer<Float> delays,
    Pointer<Float> lifetimes,
    Pointer<Float> xDrifts,
    Pointer<Float> yDrifts,
    Pointer<Double> curlSines,
    Pointer<Double> curlCosines,
    Pointer<Double> scales,
    Pointer<Double> opacities,
    Pointer<Double> offsetsX,
    Pointer<Double> offsetsY,
    Pointer<Float> horizontalEdges,
    Pointer<Float> verticalEdges,
    Pointer<Float> transforms,
    Pointer<Float> rects,
    Pointer<Int32> colors,
  );

  @Native<_TerminalPoseSignature>(
    isLeaf: true,
    symbol: 'omf_motion_terminal_pose',
    assetId: 'package:oh_my_flutter/src/widgets/motion/internals/disintegration/motion_particle_abi_native.dart',
  )
  external static int _terminalPose(
    int columns,
    int rows,
    int oldCurlColumns,
    int curlColumns,
    int firstParticle,
    int moves,
    int sampleCount,
    int firstDormantColumn,
    int omitZero,
    int updatePose,
    double progress,
    double directionCosine,
    double directionSine,
    double pivotX,
    double pivotY,
    double suffixCosine,
    double suffixSine,
    double suffixX,
    double suffixY,
    double spriteScale,
    double suffixAlpha,
    Pointer<Float> samples,
    Pointer<Double> columnCenters,
    Pointer<Double> rowCenters,
    Pointer<Double> tileCentersX,
    Pointer<Double> tileCentersY,
    Pointer<Double> tileWidths,
    Pointer<Double> tileHeights,
    Pointer<Float> delays,
    Pointer<Float> lifetimes,
    Pointer<Float> xDrifts,
    Pointer<Float> yDrifts,
    Pointer<Double> curlSines,
    Pointer<Double> curlCosines,
    Pointer<Double> scales,
    Pointer<Double> opacities,
    Pointer<Double> offsetsX,
    Pointer<Double> offsetsY,
    Pointer<Float> horizontalEdges,
    Pointer<Float> verticalEdges,
    Pointer<Float> transforms,
    Pointer<Float> rects,
    Pointer<Int32> colors,
  );
}

